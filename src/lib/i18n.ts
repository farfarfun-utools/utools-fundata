export const MESSAGES: Record<Locale, Record<I18nKey, string>> = {
  'zh-CN': ZH_CN,
  en: EN,
}

export function t(
  locale: Locale,
  key: I18nKey | string,
  params?: Record<string, string | number>,
): string {
  const dict = MESSAGES[locale] ?? MESSAGES['zh-CN']
  const template =
    (dict as Record<string, string>)[key] ?? (ZH_CN as Record<string, string>)[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, token: string) =>
    params[token] !== undefined ? String(params[token]) : `{${token}}`,
  )
}
